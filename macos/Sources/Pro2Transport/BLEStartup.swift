    public static let commandCount = commands.count
    static func initializationCommands(skipUSBInitialization: Bool) -> [Data] {
        commands.filter { !skipUSBInitialization || $0[0] != 0x03 || $0[3] != 0x0d }
    }
    public static func recognizesController(name: String, manufacturer: Data?) -> Bool {
        let lower = name.lowercased()
        let nameMatch = ["pro controller", "switch", "nintendo", "pro2", "pro 2", "ns2"].contains { lower.contains($0) }
        let bytes = manufacturer.map(Array.init) ?? []
        return nameMatch || (bytes.count >= 2 && bytes[0] == 0x53 && bytes[1] == 0x05)
    }
    public static func acknowledgementMatches(request: Data, reply: Data) -> Bool {
        let request = Array(request), reply = Array(reply)
        return request.count >= 8 && reply.count >= 8 && request[0] == reply[0] && request[3] == reply[3]
    }
    public static func reconnectDelay(attempt: Int) -> TimeInterval {
        let bounded = max(1, min(5, attempt))
        return min(15, pow(2, Double(bounded - 1)))
    }
    static let calibrationBlocks: [(UInt32, Int)] = [(0x00013040, 16), (0x00013100, 24)]
    static func flashRead(address: UInt32) -> Data {
        Data([0x02, 0x91, 0x01, 0x04, 0x00, 0x08, 0x00, 0x00, 0x09, 0x7e, 0x00, 0x00,
              UInt8(truncatingIfNeeded: address), UInt8(truncatingIfNeeded: address >> 8),
              UInt8(truncatingIfNeeded: address >> 16), UInt8(truncatingIfNeeded: address >> 24)])
    }
    static func flashPayload(reply: Data, address: UInt32, length: Int) -> Data? {
        let bytes = Array(reply)
        guard length >= 0, length <= 9, bytes.count >= 16 + length else { return nil }
        let returned = UInt32(bytes[12]) | UInt32(bytes[13]) << 8 | UInt32(bytes[14]) << 16 | UInt32(bytes[15]) << 24
        guard returned == address else { return nil }
        return Data(bytes[16..<(16 + length)])
    }
