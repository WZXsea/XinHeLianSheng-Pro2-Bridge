enum BLEBatteryRefreshPolicy {
    static func canRefresh(enabled: Bool, ready: Bool, quietSeconds: TimeInterval,
        elapsedSeconds: TimeInterval, inputAge: TimeInterval, measuredHz: Double,
        operationInFlight: Bool, suspended: Bool) -> Bool {
        enabled && ready && quietSeconds >= 5 && elapsedSeconds >= 600
            && inputAge >= 0 && inputAge < 0.5 && measuredHz >= 10 && !operationInFlight && !suspended
    }
}
